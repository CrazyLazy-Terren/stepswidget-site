import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

/*
 * Shared by `pick-widget-tiles.mjs` (automatic colour sweep) and
 * `widget-picker.mjs` (pick by hand): the wall's shape, and writing a set of
 * picks out to the site.
 */

export const columns = 6
export const rows = 4

/**
 * Where the app's export is kept between runs. Gitignored: it is ~370 PNGs,
 * and only the picked tiles (as WebP) belong in the repo.
 */
export const defaultExportDir = '.widget-export'

export const names = {
  Complete: 'Steps Ring',
  Complete2: 'Steps Timeline',
  Complete3: 'Goal Progress',
  GoalPlan: 'Walking Plan',
  Simple: 'Steps Minimal',
  SimpleText: 'Steps Prompt',
}

/** Grid cells in sweep order: anti-diagonals from the top-left, each walked top to bottom. */
export function sweepCells() {
  const cells = []
  for (let row = 0; row < rows; row++) for (let col = 0; col < columns; col++) cells.push({ row, col })
  return cells.sort((a, b) => a.row + a.col - (b.row + b.col) || a.row - b.row)
}

/** Every exported style: `{ key, type }`, in the app's catalogue order. */
export function readManifest(exportDir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(exportDir, 'manifest.json'), 'utf8'))
  return manifest
    .map(({ type, index }) => ({ key: `${type.toLowerCase()}-${index}`, type }))
    .filter(({ key }) => ['light', 'dark'].every((scheme) => fs.existsSync(path.join(exportDir, `${key}-${scheme}.png`))))
}

/** The current wall, as style keys by cell (row-major), read back from app/widget-tiles.ts. */
export function readCurrentGrid() {
  const grid = Array(columns * rows).fill(null)
  if (!fs.existsSync('app/widget-tiles.ts')) return grid
  const source = fs.readFileSync('app/widget-tiles.ts', 'utf8')
  // The list is in grid order. (Older lists were in sweep order with an
  // `lgOrder` cell per tile; read those by that.)
  ;[...source.matchAll(/id: '([^']+)'(?:.*lgOrder: (\d+))?/g)].forEach(([, key, order], index) => {
    grid[order === undefined ? index : Number(order)] = key
  })
  return grid
}

/**
 * Writes the wall: WebPs into public/assets/widgets/ and the tile list into
 * app/widget-tiles.ts.
 *
 * `picks` is `{ key, type, row, col }` per cell. The list is in grid order, row
 * by row, so the array order is the order the 6-column wall shows them in; no
 * CSS reordering. Empty cells are skipped, so later tiles move up into them.
 */
export async function writeTiles(exportDir, picks) {
  const ordered = [...picks].sort((a, b) => a.row - b.row || a.col - b.col)

  // Touch only what changed: the dev server rebuilds on every file event, and
  // clearing and rewriting the whole folder on each picker save made it grow
  // until it failed ("RangeError: Map maximum size exceeded").
  const outDir = 'public/assets/widgets'
  fs.mkdirSync(outDir, { recursive: true })
  const wanted = new Set(ordered.flatMap((p) => [`${p.key}-light.webp`, `${p.key}-dark.webp`]))
  for (const file of fs.readdirSync(outDir)) {
    if (!wanted.has(file)) fs.rmSync(path.join(outDir, file))
  }
  for (const pick of ordered) {
    for (const scheme of ['light', 'dark']) {
      const source = path.join(exportDir, `${pick.key}-${scheme}.png`)
      const target = path.join(outDir, `${pick.key}-${scheme}.webp`)
      // Same name means same render, unless the export has been retaken since.
      if (fs.existsSync(target) && fs.statSync(target).mtimeMs >= fs.statSync(source).mtimeMs) continue
      await sharp(source).webp({ quality: 88, alphaQuality: 100, effort: 4 }).toFile(target)
    }
  }

  const lines = ordered.map(
    (p) =>
      `  { id: '${p.key}', light: '/assets/widgets/${p.key}-light.webp', dark: '/assets/widgets/${p.key}-dark.webp', alt: '${names[p.type]} widget showing 5,640 of 8,000 steps', wave: ${p.row + p.col} },`,
  )
  const list = `/**
 * Home Screen widgets exported from the app. Generated by
 * \`scripts/pick-widget-tiles.mjs\` (automatic colour sweep) or
 * \`scripts/widget-picker.mjs\` (pick by hand) — regenerate rather than edit.
 *
 * In grid order, row by row: the array order is the order the wall shows them.
 * \`wave\` is the tile's diagonal on the 6-column wall, which staggers the
 * entry animation along the colour sweep.
 */
export type WidgetTile = { id: string; light: string; dark: string; alt: string; wave: number }

export const widgetTiles: readonly WidgetTile[] = [
${lines.join('\n')}
]
`
  const listFile = 'app/widget-tiles.ts'
  if (!fs.existsSync(listFile) || fs.readFileSync(listFile, 'utf8') !== list) fs.writeFileSync(listFile, list)
  return ordered.length
}
